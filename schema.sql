-- K'S Bite Express database schema
create extension if not exists pgcrypto;

create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin'))
);

create or replace function public.is_admin()
returns boolean language sql security definer set search_path = public
as $$
  select exists (
    select 1 from public.user_roles
    where user_id = auth.uid() and role = 'admin'
  );
$$;

create table if not exists public.shop_settings (
  id integer primary key check (id = 1),
  accepting_orders boolean not null default true,
  opening_time text not null default '11:30',
  closing_time text not null default '21:30'
);
insert into public.shop_settings (id, accepting_orders, opening_time, closing_time)
values (1, true, '11:30', '21:30')
on conflict (id) do nothing;

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_phone text not null,
  pickup_time text not null,
  items jsonb not null,
  total integer not null check (total >= 0),
  status text not null default 'new'
    check (status in ('new','accepted','preparing','ready','collected','rejected')),
  note text,
  created_at timestamptz not null default now()
);

alter table public.user_roles enable row level security;
alter table public.shop_settings enable row level security;
alter table public.orders enable row level security;

drop policy if exists "admins read own role" on public.user_roles;
create policy "admins read own role" on public.user_roles
for select to authenticated using (user_id = auth.uid() and public.is_admin());

drop policy if exists "public read shop settings" on public.shop_settings;
create policy "public read shop settings" on public.shop_settings
for select to anon, authenticated using (true);

drop policy if exists "admins update shop settings" on public.shop_settings;
create policy "admins update shop settings" on public.shop_settings
for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "public create new orders while open" on public.orders;
create policy "public create new orders while open" on public.orders
for insert to anon, authenticated
with check (
  status = 'new'
  and exists (select 1 from public.shop_settings where id = 1 and accepting_orders = true)
);

drop policy if exists "admins read orders" on public.orders;
create policy "admins read orders" on public.orders
for select to authenticated using (public.is_admin());

drop policy if exists "admins update orders" on public.orders;
create policy "admins update orders" on public.orders
for update to authenticated using (public.is_admin()) with check (public.is_admin());

do $$
begin
  alter publication supabase_realtime add table public.orders;
exception when duplicate_object then null;
when undefined_object then null;
end $$;

